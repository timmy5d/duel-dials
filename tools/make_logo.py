#!/usr/bin/env python3
"""Turn the Duel Dials artwork into a 240x240 RGB565 image for the round screen.

Usage: make_logo.py assets/duel_dials_logo.webp
Writes src/logo.h (the firmware image) and assets/logo_240.png (a preview).
The wide artwork is fitted to the screen width; the bands above and below are filled
with a blurred, darkened copy so the circle has no hard black edges.
"""
import sys
from PIL import Image, ImageFilter, ImageEnhance

S = 240
src = Image.open(sys.argv[1]).convert("RGB")
w, h = src.size

# Background: cover the square, blur and darken.
k = S / h
bg = src.resize((round(w * k), S), Image.LANCZOS)
x0 = (bg.width - S) // 2
bg = bg.crop((x0, 0, x0 + S, S)).filter(ImageFilter.GaussianBlur(9))
bg = ImageEnhance.Brightness(bg).enhance(0.45)

# Foreground: fit the width (with a little overscan), centred, edges feathered into the background.
fw = 250
fh = round(h * fw / w)
fg = src.resize((fw, fh), Image.LANCZOS).crop(((fw - S) // 2, 0, (fw - S) // 2 + S, fh))
mask = Image.new("L", fg.size, 255)
feather = 14
for y in range(feather):
    a = int(255 * y / feather)
    for x in range(S):
        mask.putpixel((x, y), a)
        mask.putpixel((x, fh - 1 - y), a)
top = (S - fh) // 2
bg.paste(fg, (0, top), mask)
bg.save("assets/logo_240.png")

px = bg.load()
vals = []
for y in range(S):
    for x in range(S):
        r, g, b = px[x, y]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        vals.append(((v & 0xFF) << 8) | (v >> 8))  # byte-swapped: the order LovyanGFX sprites store
with open("src/logo.h", "w") as f:
    f.write("// Duel Dials logo, 240x240 RGB565. Generated by tools/make_logo.py - do not edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n\nconstexpr int LOGO_W = 240, LOGO_H = 240;\n")
    f.write("extern const uint16_t LOGO_565[LOGO_W * LOGO_H];\n")
with open("src/logo.cpp", "w") as f:
    f.write('// Generated by tools/make_logo.py - do not edit.\n#include "logo.h"\n\n')
    f.write("const uint16_t LOGO_565[LOGO_W * LOGO_H] = {\n")
    for i in range(0, len(vals), 16):
        f.write("  " + ", ".join("0x%04X" % v for v in vals[i:i + 16]) + ",\n")
    f.write("};\n")
print("ok", fh, top)
