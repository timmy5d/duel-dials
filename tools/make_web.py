#!/usr/bin/env python3
"""Pack web/app.html (the phone companion app) into src/webapp.h as gzip bytes.

Usage: make_web.py   (run from the project folder; the build also runs it via extra_scripts)
"""
import gzip, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "web", "app.html")
dst = os.path.join(root, "src", "webapp.h")
data = gzip.compress(open(src, "rb").read(), 9, mtime=0)
lines = ["// Generated by tools/make_web.py from web/app.html - do not edit.", "#pragma once", "#include <stdint.h>",
         "#include <stddef.h>", "", f"constexpr size_t WEBAPP_GZ_LEN = {len(data)};",
         "const uint8_t WEBAPP_GZ[WEBAPP_GZ_LEN] = {"]
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join(str(b) for b in data[i:i + 20]) + ",")
lines.append("};")
out = "\n".join(lines) + "\n"
if not os.path.exists(dst) or open(dst).read() != out:
    open(dst, "w").write(out)
print(f"webapp.h: {len(data)} bytes gzip")
